'use client';

import { useActionState, useState, useTransition } from 'react';
import { Alert, FormMessage } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { TextField } from '@/components/ui/field';
import { SubmitButton } from '@/components/ui/submit-button';
import { confirmEnrollment, disableTwoFactor, startEnrollment, type Enrollment } from './actions';

/** Enable / disable TOTP 2FA. The server page passes the verified factor, if any. */
export function TwoFactorSetup({ factorId }: { factorId: string | null }) {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [startError, setStartError] = useState<string | null>(null);
  const [verifyState, verify] = useActionState(confirmEnrollment, undefined);
  const [disableState, disable] = useActionState(disableTwoFactor, undefined);
  const [starting, startTransition] = useTransition();

  if (factorId) {
    return (
      <div className="space-y-4">
        <Alert tone="success">A verificação em duas etapas está ativa nesta conta.</Alert>
        <form
          action={disable}
          onSubmit={(e) => {
            if (!confirm('Desativar a verificação em duas etapas?')) e.preventDefault();
          }}
        >
          <input type="hidden" name="factor_id" value={factorId} />
          <SubmitButton variant="secondary" pendingLabel="Desativando…">
            Desativar
          </SubmitButton>
        </form>
        <FormMessage state={disableState} />
      </div>
    );
  }

  if (enrollment && !verifyState?.ok) {
    return (
      <div className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm text-text">
          <li>
            Abra o aplicativo autenticador (Google Authenticator, Microsoft Authenticator,
            1Password…).
          </li>
          <li>Leia o QR code abaixo ou digite a chave.</li>
          <li>Digite o código de 6 números que aparecer.</li>
        </ol>
        {/* QR code is an SVG data URL generated by Supabase Auth. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={enrollment.qrCode}
          alt="QR code para o aplicativo autenticador"
          className="h-44 w-44 rounded-md border border-border bg-white p-2"
        />
        <p className="text-sm text-muted">
          Chave: <code className="break-all font-mono text-text">{enrollment.secret}</code>
        </p>
        <form action={verify} className="space-y-3">
          <input type="hidden" name="factor_id" value={enrollment.factorId} />
          <TextField
            id="code"
            label="Código"
            inputMode="numeric"
            autoComplete="one-time-code"
            maxLength={7}
            required
          />
          <FormMessage state={verifyState} />
          <SubmitButton pendingLabel="Verificando…">Ativar</SubmitButton>
        </form>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      <p className="text-sm text-text">
        Além da senha, peça um código do celular ao entrar. Recomendado para administradores.
      </p>
      <FormMessage state={verifyState ?? disableState} />
      {startError ? <Alert tone="error">{startError}</Alert> : null}
      <Button
        disabled={starting}
        onClick={() =>
          startTransition(async () => {
            const result = await startEnrollment();
            if ('error' in result) setStartError(result.error);
            else {
              setStartError(null);
              setEnrollment(result);
            }
          })
        }
      >
        {starting ? 'Preparando…' : 'Ativar verificação em duas etapas'}
      </Button>
    </div>
  );
}
